/** An element containing an icon followed by optional text. */
export function iconLabel(name: string, label?: string, size = 16): DocumentFragment {
  const frag = document.createDocumentFragment();
  frag.append(fromHtml(icon(name, size)));
  if (label) frag.append(h('span', null, label));
  return frag;
}
